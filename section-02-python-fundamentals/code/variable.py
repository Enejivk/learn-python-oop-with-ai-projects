# what is a variable?
# a variable is a container for storing data values

bottle = "water"
# bottle is the variable name
# "water" is the value stored in the variable

age = 25
# age is the variable name
# 25 is the value stored in the variable

name = "Alice"
# name is the variable name
# "Alice" is the value stored in the variable

# RULE FOR NAMING VARIABLES
# - Variable names can only contain letters, numbers, and underscores (`_`)
# school3 = "Greenwood High school"
# - A variable name **cannot** start with a number
# sch3ool3 = "Greenwood High school"
# - Variable names are **case-sensitive** — `name`, `Name`, and `NAME` are three different variables
# name = "Alice"
# Name = "Bob"
# NAME = "Charlie"
# - You cannot use Python **reserved keywords** as variable names (words like `if`, `for`, `while`, `class`, etc.)

